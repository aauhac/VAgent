def get_area_feedback(area_id: str, score: Optional[float]) -> tuple[str, list[str]]:
    template = AREA_FEEDBACK_TEMPLATES[area_id]
    if score is None:
        return "이 영역은 이번 녹음에서 안정적으로 분석하기 어려워 점수에서 제외했습니다.", []
    if score >= 70:
        return template["good"], []
    return template["needs_work"], template["practice"]
